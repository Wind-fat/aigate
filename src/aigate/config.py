"""Application settings — single source of truth, loaded from env with prefix AIGATE_."""

from __future__ import annotations

from functools import lru_cache

from pydantic import field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", env_prefix="AIGATE_", extra="ignore")

    app_name: str = "AIGate"
    version: str = "0.3.0"
    env: str = "dev"
    log_level: str = "INFO"

    # --- storage ---
    database_url: str = "sqlite+aiosqlite:///./aigate.db"
    # create_all on boot. Set false in production once Alembic owns the schema.
    auto_create_schema: bool = True

    # --- control plane auth ---
    admin_token: str = "dev-admin-token"
    # signs console session cookies; generated by scripts/setup.py
    session_secret: str = "dev-session-secret-change-me"
    # 供应商密钥的加密主密钥。留空则退化为从 session_secret 派生（启动时会告警：
    # 换 session secret = 所有已保存的供应商密钥失效）。
    secret_key: str = ""
    # 「今天」「本月」按哪个时区切分。库里一律 UTC，只有展示与账期边界用它。
    timezone: str = "Asia/Shanghai"
    session_ttl_hours: int = 12
    # Default prompt template version; requests may override with X-Prompt-Version.
    # It participates in the cache key, so bumping it invalidates the semantic cache.
    prompt_version: str = "v1"
    # "masked" (default) keeps only the PII-masked prompt. "raw" also stores what the
    # user actually typed — useful when debugging a complaint, a liability otherwise.
    trace_prompt_mode: str = "masked"
    trace_prompt_max_chars: int = 4000
    # set true once the console is served over HTTPS
    cookie_secure: bool = False

    # --- data plane ---
    default_provider: str = "mock"
    request_timeout_s: float = 30.0
    default_rpm: int = 60

    # --- rate limiting / circuit breaker ---
    rate_limiter: str = "memory"
    # 熔断器后端。留空 = 跟随 rate_limiter：多副本时两者必须一起共享。
    circuit_backend: str = ""  # memory | redis
    redis_url: str = "redis://127.0.0.1:6379/0"
    circuit_threshold: int = 3
    circuit_cooldown_s: float = 30.0

    # --- metering (batched writer) ---
    metering_batch_size: int = 100
    metering_flush_interval_ms: int = 200
    metering_queue_max: int = 10000
    # empty string disables the crash-safe spool
    metering_spool_path: str = "./aigate_metering.spool"

    # --- semantic cache ---
    semantic_cache_enabled: bool = True
    # None = use the embedder's calibrated threshold (hash 0.65 / api 0.92)
    cache_threshold: float | None = None
    cache_ttl_s: int = 86400
    cache_max_scan: int = 2000

    # --- providers ---
    openai_base_url: str = "https://api.openai.com/v1"
    openai_api_key: str = ""
    dashscope_base_url: str = "https://dashscope.aliyuncs.com/compatible-mode/v1"
    dashscope_api_key: str = ""
    deepseek_base_url: str = "https://api.deepseek.com/v1"
    deepseek_api_key: str = ""
    vllm_base_url: str = "http://127.0.0.1:8000/v1"
    vllm_api_key: str = "not-needed"

    @field_validator("cache_threshold", mode="before")
    @classmethod
    def _blank_threshold_means_default(cls, value):
        """`AIGATE_CACHE_THRESHOLD=` in a hand-edited .env must not crash startup.

        An empty value is the natural way to say "use the embedder's calibrated
        threshold", so treat blank as None instead of letting pydantic reject "".
        """
        if isinstance(value, str) and not value.strip():
            return None
        return value

    @property
    def is_sqlite(self) -> bool:
        return self.database_url.startswith("sqlite")


INSECURE_DEFAULTS = {
    "dev-admin-token",
    "dev-session-secret-change-me",
    "change-me-admin-token",
    "change-me-session-secret",
}


def assert_production_ready(settings: Settings) -> None:
    """Refuse to boot in prod with the example credentials.

    A tool that ships with `change-me` defaults and no guard is a tool that eventually
    runs in production with `change-me`. This is the cheapest possible version of that
    guard: fail loudly at startup instead of silently at the audit.
    """
    if settings.env != "prod":
        return

    problems: list[str] = []
    for name, value, minimum in (
        ("AIGATE_ADMIN_TOKEN", settings.admin_token, 24),
        ("AIGATE_SESSION_SECRET", settings.session_secret, 32),
    ):
        if value in INSECURE_DEFAULTS:
            problems.append(f"{name} is still a placeholder")
        elif len(value) < minimum:
            problems.append(f"{name} is shorter than {minimum} chars")
    if not settings.cookie_secure:
        problems.append("AIGATE_COOKIE_SECURE must be true behind HTTPS")

    if problems:
        raise RuntimeError("refusing to start with AIGATE_ENV=prod: " + "; ".join(problems))


@lru_cache
def get_settings() -> Settings:
    return Settings()
